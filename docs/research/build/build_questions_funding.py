def build_workbook():
    XLSX.mkdir(parents=True, exist_ok=True)
    path = XLSX / "16_Questions_Funding.xlsx"
    wb = xlsxwriter.Workbook(str(path), {"nan_inf_to_errors": True})

    f = {}
    f["h"] = wb.add_format(dict(bold=True, bg_color="#1E3A5F", font_color="white",
                                border=1, text_wrap=True, valign="vcenter",
                                font_size=9.5))
    f["t"] = wb.add_format(dict(text_wrap=True, valign="top", font_size=9))
    f["tb"] = wb.add_format(dict(bold=True, font_size=11, valign="top",
                                 font_color="#1E3A5F"))
    f["title"] = wb.add_format(dict(bold=True, font_size=13, font_color="#1E3A5F"))
    f["sub"] = wb.add_format(dict(text_wrap=True, valign="top", font_size=9.5,
                                  italic=True, font_color="#475569"))
    f["ok"] = wb.add_format(dict(bg_color="#DCFCE7", font_size=9, border=1))
    f["warn"] = wb.add_format(dict(bg_color="#FEF3C7", font_size=9, border=1))
    f["bad"] = wb.add_format(dict(bg_color="#FEE2E2", font_size=9, border=1))
    f["neut"] = wb.add_format(dict(bg_color="#F1F5F9", font_size=9, border=1))
    f["tot"] = wb.add_format(dict(bold=True, bg_color="#1E3A5F", font_color="white",
                                  font_size=9, border=1, text_wrap=True,
                                  valign="top"))

    def sheet(name, title, subtitle, headers, rows, widths, fmts=None,
              tot_row=None):
        ws = wb.add_worksheet(name)
        ws.write(0, 0, title, f["title"])
        ws.write(1, 0, subtitle, f["sub"])
        ws.set_row(1, 32)
        for i, hh in enumerate(headers):
            ws.write(3, i, hh, f["h"])
        ws.set_row(3, 30)
        for r, row in enumerate(rows, start=4):
            last = (tot_row is not None and r == 4 + len(rows) - 1)
            for c, hh in enumerate(headers):
                fmt = f["tot"] if last else f["t"]
                if not last and fmts and hh in fmts:
                    fmt = fmts[hh](row.get(hh, ""))
                ws.write(r, c, row.get(hh, ""), fmt)
        for c, w in enumerate(widths):
            ws.set_column(c, c, w)
        ws.freeze_panes(4, 0)
        if rows:
            ws.autofilter(3, 0, 3 + len(rows), len(headers) - 1)
        return ws

    # 1. The budget, with a totals row that reconciles.
    brows = budget_rows()
    tot = dict(name="TOTAL", Q1=sum(b["Q1"] for b in brows),
               Q2=sum(b["Q2"] for b in brows),
               Q3=sum(b["Q3"] for b in brows),
               Q4=sum(b["Q4"] for b in brows),
               computed_total=sum(b["computed_total"] for b in brows),
               share_of_envelope="100.0%", note="", evidence_status="")
    sheet("Budget",
          "The Revised Rs 6,00,000 Budget",
          "PROVISIONAL. Every line is a planning estimate; no quotation has "
          "been obtained. The arithmetic reconciles - the build fails if it "
          "does not.",
          ["name", "Q1", "Q2", "Q3", "Q4", "total", "computed_total",
           "share_of_envelope", "note", "evidence_status"],
          brows + [tot],
          [46, 11, 11, 11, 11, 12, 15, 17, 60, 32],
          {"name": lambda v: f["tb"],
           "evidence_status": lambda v: f["warn"]},
          tot_row=True)

    # 2. Quarters.
    sheet("Quarters",
          "The One-Year Roadmap",
          "Four quarters, four words, and a milestone at the end of each.",
          ["quarter", "name", "phase_word", "objective", "workstreams",
           "workstream_items", "outcome", "slide_lines", "slide_outcome",
           "budget", "evidence_status"],
          quarter_rows(),
          [9, 34, 13, 58, 34, 90, 58, 40, 19, 12, 32],
          {"quarter": lambda v: f["tb"],
           "phase_word": lambda v: f["ok"],
           "evidence_status": lambda v: f["warn"]})

    # 3. Technology budget.
    sheet("Technology Budget",
          "Inside The Rs 3,00,000 Technology Line",
          "Half the entire envelope. Do not write invented vendor costs - "
          "obtain actual quotations and estimates.",
          ["quarter", "label", "amount", "amount_display", "share_of_tech",
           "items", "evidence_status"],
          tech_rows(),
          [9, 22, 12, 15, 15, 60, 32],
          {"quarter": lambda v: f["tb"],
           "evidence_status": lambda v: f["warn"]})

    # 4. Funding evidence.
    sheet("Funding Evidence",
          "How We Prove Every Rupee",
          "For every line, the artefact that would substantiate it. The "
          "obtained count is zero across the board, and that is the point.",
          ["category", "budget_line", "amount", "amount_display", "artefacts",
           "n_artefacts", "obtained", "status", "evidence_status"],
          evidence_rows(),
          [24, 46, 12, 15, 76, 13, 10, 15, 32],
          {"status": lambda v: f["bad"],
           "obtained": lambda v: f["bad"],
           "evidence_status": lambda v: f["warn"]})

    # 5. Team.
    sheet("Team",
          "The Team For The Year",
          "Six core roles we control, seven external dependencies we do not.",
          ["kind", "role", "detail", "evidence_status"],
          team_rows(),
          [22, 32, 62, 32],
          {"kind": lambda v: f["ok"] if v == "CORE TEAM" else f["neut"],
           "evidence_status": lambda v: f["warn"]})

    # 6. What is not yet verified.
    sheet("Not Yet Verified",
          "What Is Not Yet Verified, And What Would Settle It",
          "This sheet is the reason the rest of the workbook is labelled "
          "provisional.",
          ["id", "title", "claim", "checked", "still_open"],
          unverified_rows(),
          [9, 46, 66, 76, 76],
          {"id": lambda v: f["tb"]})

    wb.close()
    return path


