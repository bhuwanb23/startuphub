def budget_rows():
    out = []
    for b in Q.BUDGET:
        row = dict(b)
        row.pop("q", None)
        row["Q1"] = b["q"][0]
        row["Q2"] = b["q"][1]
        row["Q3"] = b["q"][2]
        row["Q4"] = b["q"][3]
        row["computed_total"] = sum(b["q"])
        row["share_of_envelope"] = f"{sum(b['q']) / Q.BUDGET_TOTAL:.1%}"
        row["evidence_status"] = Q.EVIDENCE_STATUS
        out.append(row)
    return out


def quarter_rows():
    out = []
    for q in Q.QUARTERS:
        out.append(dict(
            quarter=q["id"], name=q["name"], phase_word=q["phase_word"],
            objective=q["objective"],
            workstreams="; ".join(l for l, _ in q["workstreams"]),
            workstream_items=" | ".join(
                f"{l}: {', '.join(it)}" for l, it in q["workstreams"]),
            outcome=q["outcome"],
            slide_lines="; ".join(q["slide"]),
            slide_outcome=q["slide_outcome"],
            budget=Q.rs(Q.computed_quarter_totals()[
                int(q["id"][1]) - 1]),
            evidence_status=Q.EVIDENCE_STATUS))
    return out


def tech_rows():
    out = []
    for t in Q.TECH_BUDGET:
        out.append(dict(
            quarter=t["quarter"], label=t["label"], amount=t["amount"],
            amount_display=Q.rs(t["amount"]),
            share_of_tech=f"{t['amount'] / Q.TECH_BUDGET_TOTAL:.1%}",
            items="; ".join(t["items"]),
            evidence_status=Q.EVIDENCE_STATUS))
    return out


def evidence_rows():
    cat_to_line = {
        "Technology": "Technology Development & Innovation Refinement",
        "Market Research": "Market Research & Pilot Study",
        "IP": "IP Filing & Management",
        "Incubation": "Incubation & Mentorship",
        "Registration": "Startup Registration & Consultation",
        "Competitions / Exhibitions": "Competitions / Exhibitions",
        "Contingency": "Essential Contingency",
    }
    line_by_name = {b["name"]: b for b in Q.BUDGET}
    out = []
    for ev in Q.FUNDING_EVIDENCE:
        line = cat_to_line[ev["category"]]
        b = line_by_name[line]
        out.append(dict(
            category=ev["category"], budget_line=line,
            amount=b["total"], amount_display=Q.rs(b["total"]),
            artefacts="; ".join(ev["artefacts"]),
            n_artefacts=len(ev["artefacts"]),
            obtained=0, status="NOT OBTAINED",
            evidence_status=Q.EVIDENCE_STATUS))
    return out


def team_rows():
    return [dict(role=t["role"], detail=t["detail"], kind="CORE TEAM",
                 evidence_status=Q.EVIDENCE_STATUS) for t in Q.TEAM] + \
           [dict(role=d, detail="", kind="EXTERNAL DEPENDENCY",
                 evidence_status=Q.EVIDENCE_STATUS) for d in Q.DEPENDENCIES]


def unverified_rows():
    return [dict(id=u["id"], title=u["title"], claim=u["claim"],
                 checked=u["checked"], still_open=u["open"]) for u in Q.UNVERIFIED]


