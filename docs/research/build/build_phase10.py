def build_workbook():
    XLSX.mkdir(parents=True, exist_ok=True)
    path = XLSX / "08_Competitor_Matrix.xlsx"
    wb = xlsxwriter.Workbook(str(path), {"constant_memory": False})

    base = {"font_name": "Calibri", "font_size": 10}
    fmt = {
        "title": wb.add_format({**base, "font_size": 16, "bold": True, "font_color": "#1E3A5F"}),
        "sub": wb.add_format({**base, "font_size": 10, "italic": True, "font_color": "#64748B"}),
        "h": wb.add_format({**base, "bold": True, "font_color": "white", "bg_color": "#1E3A5F",
                            "border": 1, "border_color": "#0F172A", "text_wrap": True,
                            "valign": "vcenter", "align": "center"}),
        "cell": wb.add_format({**base, "border": 1, "border_color": "#E2E8F0",
                               "valign": "top", "text_wrap": True}),
        "wrap": wb.add_format({**base, "border": 1, "border_color": "#E2E8F0",
                               "valign": "top", "text_wrap": True}),
        "ctr": wb.add_format({**base, "border": 1, "border_color": "#E2E8F0",
                              "align": "center", "valign": "vcenter"}),
        "pos": {p: wb.add_format({**base, "bold": True, "font_color": "white",
                                  "align": "center", "border": 1, "border_color": "#E2E8F0"})
                for p in ("VERIFIED", "PROVEN", "PARTIAL", "UNPROVEN")},
        "url": wb.add_format({**base, "border": 1, "border_color": "#E2E8F0",
                              "font_color": "#2563EB", "valign": "top"}),
        "note": wb.add_format({**base, "border": 1, "border_color": "#E2E8F0",
                               "bg_color": "#FFFBEB", "valign": "top", "text_wrap": True}),
    }
    for k, c in SCORE_FMT.items():
        fg = "#1E293B" if k != 3 else "#FFFFFF"
        fmt[f"s{k}"] = wb.add_format({**base, "border": 1, "border_color": "#CBD5E1",
                                      "bg_color": c, "align": "center", "valign": "vcenter",
                                      "bold": k == 3, "font_color": fg})

    def header(ws, title, sub):
        ws.write(0, 0, title, fmt["title"])
        ws.write(1, 0, sub, fmt["sub"])

    # ---- sheet 1: how to read
    ws = wb.add_worksheet("How to Read")
    ws.set_column(0, 0, 3); ws.set_column(1, 1, 118)
    ws.hide_gridlines(2)
    ws.write(0, 1, "StartupHub — Competitor Matrix", fmt["title"])
    ws.write(1, 1, f"{len(ROWS)} vendors × {len(M.DIMENSIONS)} scored capabilities · "
                   f"{len(M.DIMENSIONS) * len(ROWS)} scored cells · generated {GENERATED}",
               fmt["sub"])
    r = 3
    for line, style in [
        ("THE ONE RULE", "title"),
        ("U is not 0. An unknown is not an absence. A vendor whose website never "
         "mentions technology transfer has NOT been shown to lack it — and this matrix "
         "will not pretend otherwise.", "cell"),
        ("", None),
        ("WHY THIS MATRIX HAS A FIFTH VALUE", "title"),
        ("Phase 0 claimed 'exactly zero competitors have an IPR module'. Phase 9 falsified "
         "it: four dedicated tech-transfer platforms existed and had simply not been found. "
         "That is the exact failure mode a scoring sheet invites, so the scale carries U.", "cell"),
        ("", None),
        ("SCORING SCALE", "title"),
    ]:
        if style is None:
            r += 1
            continue
        ws.write(r, 1, line, fmt[style]); r += 1
    for k in (3, 2, 1, 0, "U"):
        ws.write(r, 1, f"   {k}  —  {M.SCALE[k]}", fmt["cell"]); r += 1
    for line, style in [
        ("", None),
        ("A 0 REQUIRES A NOTE. Every vendor scoring 0 on any dimension carries an "
         "absence_note explaining what the published scope was checked against. "
         "The build FAILS if a 0 has no substantive note. This is enforced in "
         "data_p10_matrix.py::validation() and re-checked by build/audit_phase10.py.", "cell"),
        ("", None),
        ("ABSENCE BASIS — how strong is each vendor's zero?", "title"),
        ("   COMPLETE — the vendor publishes a full feature table. A dimension missing "
         "from it is strong evidence of absence.", "cell"),
        ("   PARTIAL — the vendor publishes marketing prose only. A dimension it does "
         "not mention may simply be undocumented.", "cell"),
        ("", None),
        ("MARKET POSITION IS DERIVED, NOT ASSERTED", "title"),
        ("   VERIFIED  — 20+ third-party reviews AND a named institutional reference",
         "cell"),
        ("   PROVEN    — 10+ reviews, or a named institutional logo", "cell"),
        ("   PARTIAL   — breadth ≥ 6 AND at least one named customer", "cell"),
        ("   UNPROVEN  — no third-party proof of any kind", "cell"),
        ("These are EVIDENCE tiers, not quality tiers. A vendor can be UNPROVEN and still "
         "be excellent. UNPROVEN means nobody outside the company has demonstrated it works.", "cell"),
        ("", None),
        ("EVIDENCE COVERAGE — how much of each row is actually known", "title"),
        ("   The share of a vendor's 15 cells that are not U. A low number means the row "
         "is sparse, and a sparse row is the finding rather than a defect.", "cell"),
        ("", None),
        ("COLUMNS ADDED BY PHASE 10", "title"),
        ("   The spec listed 27 columns. Two scored dimensions were appended — TRL and "
         "YUKTI-NIR / ARIIA — because they are the surviving CRITICAL gaps (GAP-02, GAP-03) "
         "and a competitive matrix that omitted the only open capabilities would "
         "misrepresent the competitive position.", "cell"),
        ("", None),
        ("PROVENANCE", "title"),
        ("   Every row carries source, last-updated, evidence grade and confidence. "
         "0 competitor conversations have taken place; named customers are vendor-published "
         "unless graded NAMED_REFERENCE (a named person, role and organisation).", "cell"),
    ]:
        if style is None:
            r += 1
            continue
        ws.write(r, 1, line, fmt[style]); r += 1

    # ---- sheet 2: the matrix
    ws = wb.add_worksheet("Competitor Matrix")
    cols = (["Competitor", "Vendor", "Country", "Origin", "Target Customer", "Primary User",
             "Core Problem"] + [d[1] for d in M.DIMENSIONS] +
            ["Pricing", "Free/Paid", "Customer Size", "Strength", "Weakness",
             "User Reviews", "Market Position", "Evidence Grade", "Named Customers",
             "Evidence Coverage %", "Absence Basis", "Absence Note", "Source", "Last Updated"])
    header(ws, "Competitor Matrix — the scored grid",
           "36 vendors × 15 capabilities. Scores: 0 absent (note required) · 1 partial · "
           "2 native · 3 differentiator · U unknown (NOT absent).")
    for i, cname in enumerate(cols):
        ws.write(3, i, cname, fmt["h"])
    ws.set_row(3, 46)

    ordered = sorted(ROWS, key=lambda r: (-M.breadth(r), r["competitor"]))
    for ri, row in enumerate(ordered, start=4):
        vals = [
            row["competitor"], row["vendor"], row["country"], row["origin"],
            row["target_customer"], row["primary_user"], row["core_problem"],
        ]
        for i, v in enumerate(vals):
            ws.write(ri, i, v, fmt["wrap"])
        ci = 7
        for k, _, _, _ in M.DIMENSIONS:
            v = row[k]
            ws.write(ri, ci, v, fmt[f"s{v}"] if v in SCORE_FMT else fmt["sU"])
            ci += 1
        for v in (row["pricing"], row["free_paid"], row["customer_size"],
                  row["strength"], row["weakness"], row["user_reviews"]):
            ws.write(ri, ci, v, fmt["wrap"]); ci += 1
        ws.write(ri, ci, row["market_position"], fmt["pos"][row["market_position"]]); ci += 1
        for v in (row["evidence_grade"], row["customers"], row["evidence_coverage"],
                  row["absence_basis"], row["absence_note"]):
            ws.write(ri, ci, v, fmt["note"] if v == row["absence_note"] else fmt["wrap"]); ci += 1
        ws.write_url(ri, ci, row["source"], fmt["url"], row["source"]); ci += 1
        ws.write(ri, ci, row["last_updated"], fmt["ctr"])

    widths = [26, 24, 10, 20, 30, 26, 34] + [13] * 15 + \
             [34, 12, 30, 40, 40, 10, 15, 16, 30, 12, 13, 46, 40, 12]
    for i, w in enumerate(widths):
        ws.set_column(i, i, w)
    ws.freeze_panes(4, 7)
    ws.autofilter(3, 0, 3 + len(ordered), len(cols) - 1)

    # ---- sheet 3: scoring legend
    ws = wb.add_worksheet("Scoring Legend")
    header(ws, "Scoring Legend", "What each value means and how market position is derived.")
    ws.set_column(0, 0, 22); ws.set_column(1, 1, 90)
    r = 3
    ws.write(r, 0, "Score", fmt["h"]); ws.write(r, 1, "Meaning", fmt["h"]); r += 1
    for k in (3, 2, 1, 0, "U"):
        ws.write(r, 0, k, fmt[f"s{k}"]); ws.write(r, 1, M.SCALE[k], fmt["cell"]); r += 1
    r += 1
    ws.write(r, 0, "Market Position", fmt["h"]); ws.write(r, 1, "Derived rule", fmt["h"]); r += 1
    for p, rule in [
        ("VERIFIED", "reviews >= 20 AND a NAMED_REFERENCE customer"),
        ("PROVEN", "reviews >= 10, OR a NAMED_LOGO customer"),
        ("PARTIAL", "breadth >= 6 AND at least one named customer"),
        ("UNPROVEN", "none of the above — no third-party proof"),
    ]:
        ws.write(r, 0, p, fmt["pos"][p]); ws.write(r, 1, rule, fmt["cell"]); r += 1
    r += 1
    ws.write(r, 0, "Evidence Grade", fmt["h"]); ws.write(r, 1, "Meaning", fmt["h"]); r += 1
    for g, mdesc in [
        ("NAMED_REFERENCE", "a named person, role and organisation"),
        ("NAMED_LOGO", "an organisation named by the vendor, unreferenced"),
        ("VENDOR_CLAIM", "asserted by the vendor with no supporting detail"),
        ("UNKNOWN", "no evidence either way"),
    ]:
        ws.write(r, 0, g, fmt["cell"]); ws.write(r, 1, mdesc, fmt["cell"]); r += 1

    # ---- sheet 4: evidence register
    ws = wb.add_worksheet("Evidence Register")
    header(ws, "Evidence Register", "Every vendor's source, provenance and last update.")
    cols = ["Competitor", "Country", "Evidence Grade", "Named Customers", "# Named",
            "Reviews", "Confidence", "Found In", "Source", "Last Updated"]
    for i, cname in enumerate(cols):
        ws.write(3, i, cname, fmt["h"])
    for ri, row in enumerate(sorted(ROWS, key=lambda r: r["competitor"]), start=4):
        for i, v in enumerate([row["competitor"], row["country"], row["evidence_grade"],
                               row["customers"], row["customers_n"], row["user_reviews"],
                               row["confidence"], row["phase9"], None, row["last_updated"]]):
            if i == 8:
                ws.write_url(ri, i, row["source"], fmt["url"], row["source"])
            else:
                ws.write(ri, i, v, fmt["wrap"])
    for i, w in enumerate([26, 10, 18, 42, 10, 9, 14, 16, 46, 13]):
        ws.set_column(i, i, w)
    ws.freeze_panes(4, 1)
    ws.autofilter(3, 0, 3 + len(ROWS), len(cols) - 1)

    # ---- sheet 5: capability coverage
    ws = wb.add_worksheet("Capability Coverage")
    header(ws, "Capability Coverage", "How many of 36 vendors build each capability. "
                                     "Sorted by how many actually build it.")
    cols = ["Capability", "Added by Phase 10", "Known", "Unknown", "Absent", "Partial",
            "Native", "Differentiator", "% Implemented"]
    for i, cname in enumerate(cols):
        ws.write(3, i, cname, fmt["h"])
    for ri, c in enumerate(sorted(COV, key=lambda c: c["n_native"] + c["n_differentiator"]),
                           start=4):
        for i, v in enumerate([c["label"], "yes" if c["added_by_phase10"] else "",
                               c["n_known"], c["n_unknown"], c["n_absent"], c["n_partial"],
                               c["n_native"], c["n_differentiator"], c["pct_implemented"]]):
            ws.write(ri, i, v, fmt["ctr"] if i > 1 else fmt["wrap"])
    for i, w in enumerate([28, 16, 9, 10, 9, 9, 9, 15, 13]):
        ws.set_column(i, i, w)
    ws.freeze_panes(4, 1)

    # ---- sheet 6: evidence coverage
    ws = wb.add_worksheet("Evidence Coverage")
    header(ws, "Evidence Coverage", "How much of each vendor's row is actually known. "
                                   "Sparse rows are the finding.")
    cols = ["Competitor", "Evidence Coverage %", "Absence Basis", "Breadth", "Mean Score",
            "Market Position", "Reviews"]
    for i, cname in enumerate(cols):
        ws.write(3, i, cname, fmt["h"])
    for ri, row in enumerate(sorted(ROWS, key=lambda r: r["evidence_coverage"]), start=4):
        vals = [row["competitor"], row["evidence_coverage"], row["absence_basis"],
                M.breadth(row), M.depth_score(row), row["market_position"], row["user_reviews"]]
        for i, v in enumerate(vals):
            ws.write(ri, i, v, fmt["pos"][v] if v in fmt["pos"] else
                     fmt["ctr"] if i in (1, 3, 4, 6) else fmt["wrap"])
    for i, w in enumerate([26, 18, 15, 10, 12, 15, 9]):
        ws.set_column(i, i, w)
    ws.freeze_panes(4, 1)

    # ---- sheet 7: market position
    ws = wb.add_worksheet("Market Position")
    header(ws, "Market Position", "Evidence tiers, not quality tiers. Derived by rule.")
    order = ["VERIFIED", "PROVEN", "PARTIAL", "UNPROVEN"]
    counts = {p: len([r for r in ROWS if r["market_position"] == p]) for p in order}
    ws.write(3, 0, "Tier", fmt["h"]); ws.write(3, 1, "Vendors", fmt["h"])
    ws.write(3, 2, "Rule", fmt["h"]); ws.write(3, 3, "Vendors at this tier", fmt["h"])
    rr = 4
    rules = {"VERIFIED": "reviews >= 20 AND NAMED_REFERENCE",
             "PROVEN": "reviews >= 10, OR NAMED_LOGO",
             "PARTIAL": "breadth >= 6 AND a named customer",
             "UNPROVEN": "no third-party proof"}
    for p in order:
        ws.write(rr, 0, p, fmt["pos"][p])
        ws.write(rr, 1, counts[p], fmt["ctr"])
        ws.write(rr, 2, rules[p], fmt["cell"])
        ws.write(rr, 3, ", ".join(sorted(r["competitor"] for r in ROWS
                                         if r["market_position"] == p)), fmt["wrap"])
        rr += 1
    ws.set_column(0, 0, 14); ws.set_column(1, 1, 9); ws.set_column(2, 2, 34)
    ws.set_column(3, 3, 80)

    # ---- sheet 8: ecosystem platforms (context, not scored)
    ws = wb.add_worksheet("Ecosystem (context)")
    header(ws, "Ecosystem Platforms — CONTEXT, NOT SCORED",
           "Statutory infrastructure. Not vendors; included so the matrix is not read "
           "in isolation. Pricing, customer size and market position do not apply.")
    cols = ["Platform", "Operator", "Unit of Record", "What It Takes", "Returns To Institution?",
            "Threat"]
    for i, cname in enumerate(cols):
        ws.write(3, i, cname, fmt["h"])
    for ri, e in enumerate(C9.ECOSYSTEM, start=4):
        for i, v in enumerate([e["name"], e["operator"], e["unit"], e["takes"],
                               e["takes_back"], e["threat"]]):
            ws.write(ri, i, v, fmt["wrap"])
    for i, w in enumerate([24, 26, 24, 40, 56, 11]):
        ws.set_column(i, i, w)
    ws.freeze_panes(4, 1)

    # ---- sheet 9: indirect alternatives (context, not scored)
    ws = wb.add_worksheet("Indirect (context)")
    header(ws, "Indirect Alternatives — CONTEXT, NOT SCORED",
           "What institutions actually use. Mostly free. Included because a matrix of "
           "vendors alone describes a market nobody buys from.")
    cols = ["Alternative", "Real Price", "Why It Wins", "What It Cannot Do", "Threat"]
    for i, cname in enumerate(cols):
        ws.write(3, i, cname, fmt["h"])
    for ri, x in enumerate(C9.INDIRECT, start=4):
        for i, v in enumerate([x["name"], x["price"], x["why_it_wins"],
                               x["what_it_cannot_do"], x["threat"]]):
            ws.write(ri, i, v, fmt["wrap"])
    for i, w in enumerate([26, 30, 44, 52, 11]):
        ws.set_column(i, i, w)
    ws.freeze_panes(4, 1)

    wb.close()
    return path


