def write_csv(path, cols, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow(r)
    return len(rows)


def write_md(path, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    return 1


def banner():
    return (f"<!-- GENERATED by build/build_phase10.py on {GENERATED}. DO NOT EDIT BY HAND.\n"
            f"     Edit build/data_p10_matrix.py and re-run. -->\n"
            f"\n"
            f"> **0 interviews conducted. 0 competitor conversations.**\n"
            f"> Every score is drawn from a vendor's own published material. `U` means\n"
            f"> **not publicly evidenced** — it is **not** the same as absent, and the two\n"
            f"> are never merged.\n")


