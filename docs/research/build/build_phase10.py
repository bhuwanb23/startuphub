def export_matrix_csv():
    cols = (["competitor", "vendor", "country", "origin", "target_customer", "primary_user",
             "core_problem"] + [k for k, _, _, _ in M.DIMENSIONS] +
            ["pricing", "free_paid", "customer_size", "strength", "weakness", "user_reviews",
             "market_position", "evidence_grade", "customers", "customers_n", "threat",
             "confidence", "phase9", "phase10", "absence_note", "absence_basis",
             "evidence_coverage", "breadth", "source", "last_updated"])
    out = []
    for r in sorted(ROWS, key=lambda r: (-M.breadth(r), r["competitor"])):
        d = {k: r.get(k, "") for k in cols}
        d["breadth"] = M.breadth(r)
        d["phase10"] = r["phase10"]
        out.append(d)
    return write_csv(OUT / "competitor_matrix.csv", cols, out)


def export_coverage_csv():
    return write_csv(OUT / "dimension_coverage.csv",
                     ["key", "label", "added_by_phase10", "n_known", "n_unknown", "n_total",
                      "n_absent", "n_partial", "n_native", "n_differentiator",
                      "pct_implemented", "pct_of_known_native_or_better"], COV)


def export_position_csv():
    order = ["VERIFIED", "PROVEN", "PARTIAL", "UNPROVEN"]
    rules = {"VERIFIED": "reviews >= 20 AND NAMED_REFERENCE",
             "PROVEN": "reviews >= 10, OR NAMED_LOGO",
             "PARTIAL": "breadth >= 6 AND a named customer",
             "UNPROVEN": "no third-party proof"}
    rows = [dict(market_position=p,
                 n=len([r for r in ROWS if r["market_position"] == p]),
                 rule=rules[p],
                 vendors=", ".join(sorted(r["competitor"] for r in ROWS
                                          if r["market_position"] == p)))
            for p in order]
    return write_csv(OUT / "market_position.csv", ["market_position", "n", "rule", "vendors"],
                     rows)


def export_evidence_csv():
    rows = [dict(competitor=r["competitor"], country=r["country"],
                 evidence_grade=r["evidence_grade"], customers=r["customers"],
                 customers_n=r["customers_n"], reviews=r["user_reviews"],
                 confidence=r["confidence"], found_in=r["phase10"],
                 absence_basis=r["absence_basis"], evidence_coverage=r["evidence_coverage"],
                 source=r["source"], last_updated=r["last_updated"])
            for r in sorted(ROWS, key=lambda r: r["competitor"])]
    return write_csv(OUT / "evidence_register.csv",
                     ["competitor", "country", "evidence_grade", "customers", "customers_n",
                      "reviews", "confidence", "found_in", "absence_basis",
                      "evidence_coverage", "source", "last_updated"], rows)


def export_gaps_csv():
    return write_csv(OUT / "positioning_gaps.csv",
                     ["gap_id", "title", "severity", "status", "surviving_claim",
                      "nearest_competitor"], C9.POSITIONING_GAPS)


def export_legend_csv():
    rows = [dict(value=str(k), meaning=M.SCALE[k],
                 rule=("requires an absence_note" if k == 0 else
                       "NOT the same as absent" if k == "U" else ""))
            for k in (3, 2, 1, 0, "U")]
    return write_csv(OUT / "scoring_legend.csv", ["value", "meaning", "rule"], rows)


