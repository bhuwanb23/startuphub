def export_wtp_streams():
    return write_csv(OUT / "wtp_streams.csv",
                     ["n", "stream", "question", "method", "bound", "low", "high",
                      "provenance", "evidence", "direction"],
                     P.WTP_STREAMS)


def export_wtp_frames():
    b = P.wtp_bracket()
    rows = [dict(frame=f["frame"], ceiling=f["ceiling"], ceiling_lakh=round(f["ceiling"] / 1e5, 2),
                 ceiling_basis=f["ceiling_basis"], source_stream=f["stream"], read=f["read"],
                 binding=(f["frame"] == b["binding_frame"]["frame"]))
            for f in b["frames"]]
    rows.append(dict(frame="FLOOR (all frames)", ceiling=b["floor"], ceiling_lakh=round(b["floor"] / 1e5, 2),
                     ceiling_basis=b["floor_basis"], source_stream="1,6", read=b["note"],
                     binding=False))
    return write_csv(OUT / "wtp_frames.csv",
                     ["frame", "ceiling", "ceiling_lakh", "ceiling_basis", "source_stream",
                      "read", "binding"], rows)


def export_procurement_bands():
    ps = P.PROCUREMENT_SUMMARY
    rows = [dict(band=b["band"], rule=b["rule"], mechanism=b["mechanism"],
                 competition=b["competition"], implication=b["implication"],
                 source=b["source"], url=b["url"]) for b in P.PROCUREMENT_BANDS]
    rows.append(dict(
        band="StartupHub position",
        rule=(f"list price {rs(P.INTERNAL_ANCHORS['list_price'])} sits inside the L1 band; "
              f"Scenario B {rs(P.INTERNAL_ANCHORS['required_acv'])} sits above the reverse-auction floor"),
        mechanism="n/a", competition="n/a",
        implication=("List price avoids auction pressure. Scenario B would require winning a "
                     f"reverse auction at the {rs(ps['reverse_auction_floor'])} threshold."),
        source="derived", url=""))
    return write_csv(OUT / "procurement_bands.csv",
                     ["band", "rule", "mechanism", "competition", "implication", "source", "url"],
                     rows)


def export_per_student():
    sizes = [500, 1000, 2000, 5000]
    series = [
        ("Fedena Standard (flat)", lambda s: 50_000, "flat per institution"),
        ("Fedena Ultimate (flat)", lambda s: 100_000, "flat per institution"),
        ("EduZenAI Enterprise (base + per-student)",
         lambda s: 20_000 + max(0, s - 300) * 70, "base Rs 20,000 + Rs 70/student above 300"),
        ("Campusify Plus (per-student)", lambda s: s * 99 * 12, "Rs 99/student/month"),
        ("DHONDI college (per-student)", lambda s: s * 1000, "Rs 1,000/student/year"),
    ]
    rows = []
    for name, fn, basis in series:
        for s in sizes:
            rows.append(dict(series=name, students=s, annual_inr=fn(s),
                             annual_lakh=round(fn(s) / 1e5, 2), basis=basis))
    return write_csv(OUT / "per_student_normalisation.csv",
                     ["series", "students", "annual_inr", "annual_lakh", "basis"], rows)


