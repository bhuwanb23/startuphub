def review_rows():
    out = []
    for r in R.REVIEWS:
        g = next(x for x in R.GRADES if x[0] == r["grade"])
        out.append(dict(
            review_id=r["id"], vendor=r["vendor"], platform=r["platform"],
            evidence_grade=r["grade"], grade_family=g[2], may_claim=g[3],
            rating=r["rating"] if r["rating"] is not None else "",
            review_date=r["date"], title=r["title"], reviewer_role=r["role"],
            reviewer_org=r["org"], org_size=r["org_size"], tenure=r["tenure"],
            incentive_flagged="YES" if r["incentive"] else "NO",
            pain_category=r["pain"],
            dislike_verbatim=r["dislike"] or "",
            switched_from=r["switched_from"] or "",
            verbatim_verified="YES" if r["verified"] else "SNIPPET-ONLY",
            source_url=r["url"], retrieved_on=R.RETRIEVED,
        ))
    return out


def platform_rows():
    have = defaultdict(set)
    for r in R.REVIEWS:
        have[r["platform"]].add(r["grade"])
    out = []
    for code, desc, status in R.PLATFORMS:
        grades = sorted(have.get(code, []))
        out.append(dict(
            platform=code, description=desc, access=status,
            records_in_corpus=len([r for r in R.REVIEWS if r["platform"] == code]),
            grades_present="; ".join(grades) or "-",
            vendors_reached=len({r["vendor"] for r in R.REVIEWS
                                 if r["platform"] == code}),
            usable_as_user_voice="YES" if (set(grades) & CLAIM) else "NO",
        ))
    return out


def complaint_rows():
    out = []
    for r in R.REVIEWS:
        if r["grade"] not in CLAIM:
            continue
        cat = next(c for c in R.PAIN_CATEGORIES if c[0] == r["pain"])
        out.append(dict(
            complaint_id=r["id"], vendor=r["vendor"], platform=r["platform"],
            pain_category=r["pain"], pain_label=cat[1],
            origin=cat[3], reviewer_role=r["role"], reviewer_org=r["org"],
            incentive_flagged="YES" if r["incentive"] else "NO",
            verbatim=r["dislike"] or "(no dissatisfaction recorded)",
            source_url=r["url"], retrieved_on=R.RETRIEVED,
        ))
    return out


def taxonomy_rows():
    counts = Counter(r["pain"] for r in R.REVIEWS if r["grade"] in CLAIM)
    claim_counts = Counter(r["pain"] for r in R.REVIEWS)
    out = []
    for code, label, origin, meaning in R.PAIN_CATEGORIES:
        out.append(dict(
            category=code, label=label, origin=origin, meaning=meaning,
            records=claim_counts.get(code, 0),
            usable_claims=counts.get(code, 0),
            vendors=len({r["vendor"] for r in R.REVIEWS
                         if r["pain"] == code and r["grade"] in CLAIM}),
        ))
    return out


def vendor_rows():
    out = []
    for name in sorted(MATRIX_NAMES):
        rs = [r for r in R.REVIEWS if r["vendor"] == name]
        us = [r for r in rs if r["grade"] in CLAIM]
        mx = next((m for m in MATRIX if m["competitor"] == name), None)
        pains = Counter(r["pain"] for r in us)
        out.append(dict(
            vendor=name,
            in_matrix="YES",
            reviews_retrieved=len(rs),
            user_voice_records=len(us),
            platforms="; ".join(sorted({r["platform"] for r in rs})) or "-",
            incentive_flagged=sum(1 for r in rs if r["incentive"]),
            top_pain=pains.most_common(1)[0][0] if pains else "-",
            pain_count=pains.most_common(1)[0][1] if pains else 0,
            matrix_user_reviews=(mx["user_reviews"] if mx else 0) or 0,
            matrix_position=(mx["market_position"] if mx else "-"),
            note=("Has user voice" if us else
                  "No retrievable user voice; competitor-site research only"),
        ))
    for extra in ("SanchiApp", "IncuMan", "ESI Incubation Centre OS"):
        if extra not in MATRIX_NAMES:
            out.append(dict(vendor=extra, in_matrix="NO", reviews_retrieved=0,
                            user_voice_records=0, platforms="-", incentive_flagged=0,
                            top_pain="-", pain_count=0, matrix_user_reviews=0,
                            matrix_position="-",
                            note="Phase 11 discovery - absent from the matrix"))
    return out


def conflict_rows():
    return [dict(vendor=c["vendor"], sources_disagreeing=c["sources"],
                 resolution=c["resolved"], impact=c["impact"]) for c in R.CONFLICTS]


def exclusion_rows():
    return [dict(vendor=v, platform=p, outcome=o, note=n)
            for v, p, o, n in R.COVERAGE_NOTES]


