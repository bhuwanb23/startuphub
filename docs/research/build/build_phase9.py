def export_competitors():
    rows = []
    for c in C.COMPETITORS:
        rows.append(dict(
            name=c["name"], vendor=c["vendor"], category=c["category"],
            subcategory=c.get("sub") or "", subcategory_label=(
                C.GLOBAL_SUBCATEGORIES.get(c["sub"], "") if c.get("sub") else ""),
            market=c["market"], origin=c["origin"], founded=c["founded"],
            pricing=c["pricing"],
            price_inr_low=c.get("price_inr_low"), price_inr_high=c.get("price_inr_high"),
            scope=c["scope"], differentiator=c["differentiator"], weakness=c["weakness"],
            evidence_grade=c["evidence"], customers=c["customers"],
            customers_n=c["customers_n"], reviews=c["reviews"], threat=c["threat"],
            breadth=sum(1 for v in c["features"].values() if v),
            india_readiness=((2 if c["market"] == "India" else 0)
                             + c["features"].get("datares", 0) + c["features"].get("nocost", 0)),
            url=c["url"], confidence=c["confidence"], retrieved=C.RETRIEVED,
        ))
    return write_csv(OUT / "competitors.csv",
                     ["name", "vendor", "category", "subcategory", "subcategory_label",
                      "market", "origin", "founded", "pricing", "price_inr_low",
                      "price_inr_high", "scope", "differentiator", "weakness",
                      "evidence_grade", "customers", "customers_n", "reviews", "threat",
                      "breadth", "india_readiness", "url", "confidence", "retrieved"], rows)


