def diff_rows():
    out = []
    for d in G.DIFFERENTIATORS:
        out.append(dict(
            n=d["n"], name=d["name"], gaps="; ".join(d["gaps"]),
            statement=d["statement"], why_it_is_a_gap=d["why"],
            evidence_a=d["evidence_a"], evidence_u=d["evidence_u"],
            vendors_holding=len(d["contested_by"]),
            contested_by="; ".join(d["contested_by"]) or "none",
            contested_note=d["contested_note"], falsifier=d["falsifier"],
            our_edge=d["our_edge"], confidence=d["confidence"]))
    p = G.PACKAGING_REQUIREMENT
    out.append(dict(
        n=0, name=p["name"], gaps="; ".join(p["gaps"]), verdict=p["verdict"],
        statement=p["reason"], why_it_is_a_gap=p["evidence"],
        evidence_a="n/a - pricing shape", evidence_u="n/a - OQ-03 unmeasured",
        vendors_holding="", contested_by="", contested_note=p["evidence"],
        falsifier="A university procurement rule that requires per-user or per-module "
                  "pricing would remove the constraint entirely.",
        our_edge="Phase 8 evidence. Fedena at Rs 1.0L flat unlimited users is the "
                 "price of admission, not an advantage.",
        confidence="n/a - packaging"))
    return out


def gap_rows():
    out = []
    for g in G.GAP_SCORECARD:
        out.append(dict(
            gap_id=g["id"], title=g["title"], severity=g["severity"],
            verdict=g["verdict"], measured_as=g["dim"] or "not a matrix dimension",
            vendors_holding=g["holders"] if g["holders"] is not None else "",
            joined_count=g["joined_n"],
            holders="; ".join(g["holders_list"]) or "-",
            joined="; ".join(g["joined_list"]) or "-",
            note=g["note"], phase11_effect=g["phase11_effect"]))
    return out


def coverage_rows_flat():
    out = []
    for c in COV:
        out.append(dict(
            vendor=c["vendor"], evidence_grade=c["evidence_grade"],
            matrix_position=c["position"],
            **{f"D{n}_score": c[f"d{n}"] for n in range(1, 7)},
            differentiators_held=c["differentiators_held"], held=c["held"]))
    return out


def features_rows():
    return [dict(section=n, name=name, verdict=verdict, note=note)
            for n, name, verdict, note in G.FEATURES_MAP]


def modules_rows():
    return [dict(module=name, verdict=verdict, rationale=why, timing=when)
            for name, verdict, why, when in G.MODULES_MAP]


def win_rows():
    return [dict(strategy=s["strategy"], why=s["why_it_works"],
                 applies_to="; ".join(f"D{n}" for n in s["applies_to"]),
                 risk=s["risk"]) for s in G.WIN_STRATEGIES]


