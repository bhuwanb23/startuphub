def build_workbook():
    XLSX.mkdir(parents=True, exist_ok=True)
    path = XLSX / "10_Feature_Gap.xlsx"
    wb = xlsxwriter.Workbook(str(path), {"nan_inf_to_errors": True})

    f = {}
    f["h"] = wb.add_format(dict(bold=True, bg_color="#1E3A5F", font_color="white",
                                border=1, text_wrap=True, valign="vcenter",
                                font_size=9.5))
    f["t"] = wb.add_format(dict(text_wrap=True, valign="top", font_size=9))
    f["tb"] = wb.add_format(dict(bold=True, font_size=11, valign="top",
                                 font_color="#1E3A5F"))
    f["title"] = wb.add_format(dict(bold=True, font_size=13, font_color="#1E3A5F"))
    f["sub"] = wb.add_format(dict(text_wrap=True, valign="top", font_size=9.5,
                                  italic=True, font_color="#475569"))
    f["ok"] = wb.add_format(dict(bg_color="#DCFCE7", font_size=9, border=1))
    f["warn"] = wb.add_format(dict(bg_color="#FEF3C7", font_size=9, border=1))
    f["bad"] = wb.add_format(dict(bg_color="#FEE2E2", font_size=9, border=1))
    f["neut"] = wb.add_format(dict(bg_color="#F1F5F9", font_size=9, border=1))

    VC = {"SURVIVES": f["ok"], "NARROWED": f["warn"], "CONTESTED": f["warn"],
          "RETIRED": f["bad"], "SURVIVES_AS_REQUIREMENT": f["ok"]}
    TC = {"EVIDENCED": f["ok"], "DEFERRED": f["neut"], "SATURATED": f["neut"],
          "CONTRADICTED": f["bad"], "NEEDS_PRIMARY": f["warn"]}

    def sheet(name, title, subtitle, headers, rows, widths, fmts=None):
        ws = wb.add_worksheet(name)
        ws.write(0, 0, title, f["title"])
        ws.write(1, 0, subtitle, f["sub"])
        ws.set_row(1, 30)
        for i, hh in enumerate(headers):
            ws.write(3, i, hh, f["h"])
        ws.set_row(3, 30)
        for r, row in enumerate(rows, start=4):
            for c, hh in enumerate(headers):
                fmt = f["t"]
                if fmts and hh in fmts:
                    fmt = fmts[hh](row.get(hh, ""))
                ws.write(r, c, row.get(hh, ""), fmt)
        for c, w in enumerate(widths):
            ws.set_column(c, c, w)
        ws.freeze_panes(4, 0)
        if rows:
            ws.autofilter(3, 0, 3 + len(rows), len(headers) - 1)
        return ws

    sheet("Differentiators",
          "The Six Differentiators",
          "Six, not thirteen. Rule 1 retired the saturated capabilities the earlier "
          "gaps leaned on. Row 0 is a packaging requirement, not a differentiator.",
          ["n", "name", "gaps", "statement", "why_it_is_a_gap", "evidence_a",
           "evidence_u", "vendors_holding", "contested_by", "contested_note",
           "falsifier", "our_edge", "confidence"],
          diff_rows(),
          [4, 34, 10, 56, 62, 44, 44, 14, 34, 44, 52, 58, 24],
          {"n": lambda v: f["tb"]})

    sheet("Gap Scorecard",
          "All 13 Gaps Re-Scored Against 40 Vendors",
          "GAP-03 was 'the highest-value and most-defensible gap in the category' "
          "three phases ago. It is now contested by entrants with no customer proof.",
          ["gap_id", "title", "severity", "verdict", "measured_as",
           "vendors_holding", "joined_count", "holders", "joined", "note",
           "phase11_effect"],
          gap_rows(), [9, 46, 11, 24, 22, 15, 14, 54, 46, 78, 58],
          {"verdict": lambda v: VC.get(v, f["neut"]),
           "severity": lambda v: f["bad"] if v == "CRITICAL" else
           f["warn"] if v == "HIGH" else f["neut"]})

    sheet("Competitor Coverage",
          "Which Of The Six Does Each Vendor Already Have",
          f"{S['vendors_holding_any']} of {S['vendors']} vendors hold at least one; "
          f"{S['vendors_holding_two']} hold two or more.",
          ["vendor", "evidence_grade", "matrix_position"] +
          [f"D{n}_score" for n in range(1, 7)] +
          ["differentiators_held", "held"],
          coverage_rows_flat(),
          [30, 18, 16] + [10] * 6 + [20, 16],
          {"D1_score": lambda v: f["ok"] if v >= 2 else f["neut"],
           "D2_score": lambda v: f["ok"] if v >= 2 else f["neut"],
           "evidence_grade": lambda v: f["bad"] if v == "UNKNOWN" else f["warn"]})

    sheet("features.md Triage",
          "docs/features.md - All 46 Sections, Triaged",
          "Nothing silently dropped. EVIDENCED is backed by a differentiator or a "
          "Phase 1 documented problem.",
          ["section", "name", "verdict", "note"], features_rows(),
          [9, 42, 17, 96], {"verdict": lambda v: TC.get(v, f["neut"])})

    sheet("Module Triage", "The 12 Modules, Placed",
          "Five v1 core, three parity requirements, four v3+. Intelligence Layer is "
          "internal infrastructure only.",
          ["module", "verdict", "rationale", "timing"], modules_rows(),
          [28, 17, 66, 24], {"verdict": lambda v: TC.get(v, f["neut"])})

    sheet("How We Win",
          "Contested-Gap Strategy",
          "Every differentiator carries a falsifier AND an operational answer to "
          "'someone already does this'.",
          ["strategy", "why_it_works", "applies_to", "risk"], win_rows(),
          [30, 78, 16, 68])

    sheet("Saturation Test",
          "Rule 1 - Why This Phase Landed On Six",
          "A capability held natively or better by half the market cannot be a "
          "differentiator. This retires reporting, analytics and incubation.",
          ["capability", "vendors_native", "of_total", "share", "can_differentiate"],
          [dict(capability=c["label"],
                vendors_native=c["n_native"] + c["n_differentiator"],
                of_total=S["vendors"],
                share=round((c["n_native"] + c["n_differentiator"]) / S["vendors"], 4),
                can_differentiate="NO - RETIRED" if
                (c["n_native"] + c["n_differentiator"]) / S["vendors"]
                >= G.SATURATION_THRESHOLD else "yes")
           for c in sorted(M.dimension_coverage(G.ROWS),
                           key=lambda c: -(c["n_native"] + c["n_differentiator"]))],
          [30, 18, 12, 12, 20],
          {"can_differentiate": lambda v: f["bad"] if v.startswith("NO") else f["ok"]})

    sheet("Evidence Basis",
          "What Each Differentiator Rests On",
          "Competitor absence is measured. User demand is 24 records, none from an "
          "Indian university. They are not interchangeable.",
          ["differentiator", "evidence_A_absence", "evidence_U_demand", "confidence",
           "may_claim_user_demand"],
          [dict(differentiator=f"D{n}  {DIFFS[n]['name']}",
                evidence_A_absence=DIFFS[n]["evidence_a"],
                evidence_U_demand=DIFFS[n]["evidence_u"],
                confidence=DIFFS[n]["confidence"],
                may_claim_user_demand="NO") for n in range(1, 7)],
          [44, 58, 58, 26, 22],
          {"may_claim_user_demand": lambda v: f["bad"]})

    wb.close()
    return path


