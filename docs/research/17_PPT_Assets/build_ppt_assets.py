def lakh(n):
    """Indian grouping: 123411 -> 1,23,411."""
    s = str(int(n))
    if len(s) <= 3:
        return s
    head, tail = s[:-3], s[-3:]
    parts = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    if head:
        parts.insert(0, head)
    return ",".join(parts) + "," + tail


def short_lakh(n):
    """Compact form for chart labels: 123411 -> 1.23L."""
    if n >= 100000:
        return f"{n / 100000:.2f}L"
    return f"{n:,}"


